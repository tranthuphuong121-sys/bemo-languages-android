import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const handlers={};
const store=new Map();
const deleted=[];
let network=true;
const response=(body)=>({ok:true,body,clone(){return response(body)}});
const cache={async match(req){return store.get(typeof req==='string'?req:req.url)},async put(req,res){store.set(typeof req==='string'?req:req.url,res)},async addAll(files){for(const f of files)store.set(f,response('offline'))}};
const caches={async open(){return cache},async keys(){return ['bemo-languages-v46','bemo-languages-v47','another-app-cache']},async delete(key){deleted.push(key);return true}};
const ctx={caches,location:{origin:'https://bemo.test'},URL,Response,Promise,fetch:async()=>{if(!network)throw Error('offline');return response('online')},self:{addEventListener(n,fn){handlers[n]=fn},skipWaiting:async()=>{},clients:{claim:async()=>{}}}};
vm.runInNewContext(fs.readFileSync(new URL('../www/sw.js',import.meta.url),'utf8'),ctx);
let promise;handlers.activate({waitUntil(p){promise=p}});await promise;
assert.deepEqual(deleted,['bemo-languages-v46','bemo-languages-v47'],'Only BeMo caches should be removed');
const request={method:'GET',url:'https://bemo.test/index.html',mode:'navigate'};
store.set(request.url,response('offline copy'));
handlers.fetch({request,respondWith(p){promise=p}});
assert.equal((await promise).body,'online','Navigation should prefer network');
network=false;handlers.fetch({request,respondWith(p){promise=p}});
assert.equal((await promise).body,'online','Navigation should fall back to cached copy');
console.log('PASS: scoped cache cleanup, online navigation and offline fallback');
